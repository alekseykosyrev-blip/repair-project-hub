import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
const w=new Window({url:'https://example.org/'});
const d=w.document;
d.body.innerHTML='<div id="app"></div><dialog id="modal"></dialog><input id="importFile" type="file"><div id="toast"></div>';
if(!w.HTMLDialogElement.prototype.showModal)w.HTMLDialogElement.prototype.showModal=function(){this.open=true};
if(!w.HTMLDialogElement.prototype.close)w.HTMLDialogElement.prototype.close=function(){this.open=false};
globalThis.window=w;
globalThis.document=d;
globalThis.localStorage=w.localStorage;
Object.defineProperty(globalThis,'navigator',{configurable:true,value:w.navigator});
globalThis.FormData=w.FormData;
globalThis.confirm=()=>true;
w.localStorage.clear();
await import('../crm-app.mjs');
const click=(selector)=>{const b=d.querySelector(selector);assert.ok(b,'missing control '+selector);b.click()};
const submit=values=>{
 const dialog=d.getElementById('modal');const form=dialog.querySelector('form');assert.ok(form,'missing modal form');
 for(const [key,value] of Object.entries(values)){
  const input=form.querySelector('[name="'+key+'"]');assert.ok(input,'missing form field '+key);
  if(input.type==='checkbox')input.checked=Boolean(value);else input.value=String(value);
 }
 form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
};
assert.ok(d.body.textContent.includes('Обзор компании'));
click('[data-action="newProject"]');
submit({title:'Коттедж тест',client:'Клиент'});
assert.ok(d.body.textContent.includes('Коттедж тест'));
click('[data-action="nav"][data-view="rates"]');
click('[data-action="newRate"]');
submit({title:'Подготовка стен',unit:'м²',price:'1300',approved:true});
assert.ok(d.body.textContent.includes('Подготовка стен'));
click('[data-action="nav"][data-view="projects"]');
click('[data-action="openProject"]');
click('[data-action="tab"][data-tab="estimates"]');
click('[data-action="newEstimate"]');
submit({title:'Отделочные работы'});
click('[data-action="openEstimate"]');
click('[data-action="newLine"]');
const rateId=JSON.parse(w.localStorage.getItem('repairCRM2_v1')).rates[0].id;
submit({room:'Кухня',name:'Подготовка стен',quantity:'10',unit:'м²',rateId});
assert.ok(d.body.textContent.includes('13 000'),'Price multiplication visible');
click('[data-action="approveEstimate"]');
click('[data-action="tab"][data-tab="acts"]');
click('[data-action="newAct"]');
submit({number:'Акт 01',amount:'13000'});
click('[data-action="tab"][data-tab="payments"]');
click('[data-action="newPayment"]');
submit({amount:'6000',note:'Первый транш'});
let data=JSON.parse(w.localStorage.getItem('repairCRM2_v1'));
assert.equal(data.projects[0].payments.length,1);
assert.equal(data.projects[0].acts.length,1);
assert.equal(data.projects[0].estimates[0].approved,true);
click('[data-action="newPayment"]');
submit({amount:'7000',note:'Остаток'});
click('[data-action="closeProject"]');
data=JSON.parse(w.localStorage.getItem('repairCRM2_v1'));
assert.equal(data.projects[0].status,'closed','Closure persisted');
assert.equal(data.projects[0].payments.reduce((s,x)=>s+x.amountCents,0),1_300_000);
await w.happyDOM.abort();
console.log('CRM v2 UI smoke: object, rate, estimate, act, 2 payments, closure passed');
