import assert from 'node:assert/strict';
import * as c from '../crm-core.mjs';
const db=new Map(),storage={getItem:k=>db.get(k)??null,setItem:(k,v)=>db.set(k,String(v))};
assert.deepEqual(c.read(storage).projects,[]);
const s=c.blank(),p=c.newProject(s,'Коттедж / объект','Клиент');
const e=c.newEstimate(p,'Малярные работы');
const missing=c.addLine(s,p,e,'Гостиная','Шпаклёвка стен','12,5','м²');
assert.equal(c.estimateTotal(e).missing,1);
assert.throws(()=>c.approveEstimate(e),/расценок/);
assert.throws(()=>c.addRate(s,'Без подтверждения','м²','1500',false),/утверждена/);
const rate=c.addRate(s,'Шпаклёвка стен','м²','1 500,50',true);
c.assignRate(s,e,missing.id,rate.id);
assert.equal(missing.priceCents,150050);
assert.equal(c.estimateTotal(e).priced,1875625,'12.5 * 1500.50 = 18756.25 ₽');
assert.equal(c.approveEstimate(e),1875625);
assert.throws(()=>c.addLine(s,p,e,'Гостиная','Чужая работа','1','м²',rate.id),/Согласованную/);
assert.throws(()=>c.removeLine(e,missing.id),/Согласованную/);
assert.throws(()=>c.approveEstimate(e),/уже/);
assert.throws(()=>c.addAct(p,e.id,'20000','Акт 1'),/превысят/);
c.addAct(p,e.id,'10 000','Акт 1');
assert.equal(c.summary(p).acted,1_000_000);
assert.throws(()=>c.closeProject(p),/Не все/);
c.addAct(p,e.id,'8 756,25','Акт 2');
assert.equal(c.summary(p).unacted,0);
assert.throws(()=>c.closeProject(p),/неоплаченная/);
const pay1=c.addPayment(p,'10 000','Аванс');
assert.equal(c.summary(p).received,1_000_000);
c.reversePayment(p,pay1.id,'Ошибочная оплата');
assert.equal(c.summary(p).received,0);
assert.equal(p.payments.length,1,'Reversal must preserve payment');
assert.throws(()=>c.reversePayment(p,pay1.id,'Повторная ошибка'),/уже отменена/);
c.addPayment(p,'18 756,25','Полная оплата');
assert.equal(c.summary(p).contractRemainder,0);
assert.equal(c.summary(p).toCollect,0);
c.addExpense(p,'Материалы','Материалы','4 000');
assert.equal(c.summary(p).profit,1_475_625);
c.closeProject(p);
assert.equal(p.status,'closed');
assert.throws(()=>c.closeProject(p),/уже закрыт/);
c.addTask(p,'Проверить фасад','2026-11-07');
assert.equal(c.summary(p).tasksOpen,1);
assert.equal(c.cents('1 234,50'),123450);
assert.throws(()=>c.cents('1234.567'),/корректную сумму/);
assert.throws(()=>c.quantity('0'),/больше нуля/);
assert.equal(c.amount(12500,150050),1875625);
const saved=c.write(s,storage);
assert.equal(c.read(storage).projects.length,1);
c.addTask(p,'Вторая задача');
c.write(s,storage);
assert.ok(db.get(c.BACKUP).includes('Проверить фасад'));
assert.equal(saved.version,2);
const legacy={projects:[{id:100,name:'Старый объект',client:'Заказчик',status:'В работе',notes:'Текст',tasks:[{id:1,text:'Купи материал',done:false}],files:[{name:'Смета.pdf'}]}]};
storage.setItem(c.LEGACY,JSON.stringify(legacy));
assert.equal(c.legacyPreview(storage).count,1);
assert.equal(c.importLegacy(s,storage),1);
assert.equal(c.importLegacy(s,storage),0,'Legacy import is idempotent');
assert.equal(s.projects.length,2);
assert.equal(JSON.parse(storage.getItem(c.LEGACY)).projects.length,1,'Legacy base remains unmodified');
assert.equal(s.projects[0].legacyInfo.documentCount,1);
storage.setItem(c.STORE,'{invalid');
assert.throws(()=>c.read(storage),/повреждено/);
assert.equal(db.get(c.STORE),'{invalid','Corruption must not be silently overwritten');
console.log('CRM v2: finance, approval, acts, payments, legacy import, backup, corrupt-store protection passed');
